SELECT
    a.email,
    al.created_at,
    al.action_type,
    CASE al.action_type
        -- Account status
        WHEN 1 THEN 'UPDATE_ACCOUNT_STATUS_TO_PAID'
        WHEN 2 THEN 'UPDATE_ACCOUNT_STATUS_TO_FREE'
        WHEN 3 THEN 'UPDATE_ACCOUNT_STATUS_TO_ATTENTION'

        -- Core usage
        WHEN 100 THEN 'TRANSLATION_CALL'
        WHEN 101 THEN 'PDF_DOWNLOAD_CALL'

        -- Buttons
        WHEN 200 THEN 'BUTTON_CLICK_START_USING'
        WHEN 201 THEN 'BUTTON_CLICK_WANT_PREMIUM'
        WHEN 202 THEN 'BUTTON_CLICK_ACCEPT_COOKIES'
        WHEN 203 THEN 'BUTTON_CLICK_REJECT_COOKIES'
        WHEN 204 THEN 'BUTTON_CLICK_FAQ'
        WHEN 205 THEN 'BUTTON_CLICK_CHANGE_DIFFICULTY'
        WHEN 206 THEN 'BUTTON_CLICK_CHANGE_DIFFICULTY_ADAPTIVE'
        WHEN 207 THEN 'BUTTON_CLICK_CHANGE_DIFFICULTY_BEGINNER'
        WHEN 208 THEN 'BUTTON_CLICK_CHANGE_DIFFICULTY_AVERAGE'
        WHEN 209 THEN 'BUTTON_CLICK_CHANGE_DIFFICULTY_ADVANCED'
        WHEN 210 THEN 'BUTTON_CLICK_SUBSCRIPTION'
        WHEN 211 THEN 'BUTTON_CLICK_START_LEARNING'
        WHEN 212 THEN 'BUTTON_CLICK_LEARN_MORE'
        WHEN 213 THEN 'BUTTON_CLICK_RULE_PREVIEW'
        WHEN 214 THEN 'BUTTON_CLICK_START_USING_TEACHER_APP'
        WHEN 215 THEN 'BUTTON_CLICK_START_USING_TEACHER_PDF'

        -- Pages
        WHEN 300 THEN 'PAGE_OPEN_TRAINER'
        WHEN 301 THEN 'PAGE_OPEN_ANALYTICS'

        -- Modals
        WHEN 400 THEN 'MODAL_SHOWN_COOKIES'
        WHEN 401 THEN 'MODAL_SHOWN_TOU'
        WHEN 402 THEN 'MODAL_SHOWN_DISCOUNT_SUBSCRIPTION'

        -- Teacher
        WHEN 500 THEN 'USER_TEACHER_REGISTERED'

        -- Landing timing / scroll
        WHEN 900 THEN 'LANDING_WAIT_3_SECONDS'
        WHEN 901 THEN 'LANDING_WAIT_10_SECONDS'
        WHEN 902 THEN 'LANDING_WAIT_20_SECONDS'
        WHEN 903 THEN 'LANDING_SCROLL_START'

        ELSE 'UNKNOWN_ACTION'
        END AS action_name
FROM account_log al
         JOIN accounts a
              ON a.id = al.account_id
WHERE a.email IS NOT NULL
ORDER BY al.created_at DESC;
