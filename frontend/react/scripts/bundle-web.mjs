import {spawnSync} from "node:child_process";
import {existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync} from "node:fs";
import {dirname, extname, relative, resolve} from "node:path";
import {fileURLToPath} from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const reactRoot = resolve(scriptDir, "..");
const webRoot = resolve(reactRoot, "../web");
const buildDir = resolve(reactRoot, ".web-build");
const outputFile = resolve(reactRoot, "src/generated/webBundle.js");
const apiBaseUrl = process.env.GOODLANG_API_BASE_URL || "https://api.goodlang.app";

const build = spawnSync(
    "npm",
    ["run", "build", "--", "--config", "vite.native.config.js", "--outDir", buildDir, "--emptyOutDir"],
    {
        cwd: webRoot,
        env: {
            ...process.env,
            VITE_API_BASE_URL: apiBaseUrl,
        },
        encoding: "utf8",
        stdio: "inherit",
    },
);

if (build.status !== 0) {
    process.exit(build.status || 1);
}

function listFiles(directory) {
    return readdirSync(directory).flatMap((name) => {
        const path = resolve(directory, name);
        return statSync(path).isDirectory() ? listFiles(path) : [path];
    });
}

const mimeTypes = {
    ".avif": "image/avif",
    ".gif": "image/gif",
    ".ico": "image/x-icon",
    ".jpeg": "image/jpeg",
    ".jpg": "image/jpeg",
    ".png": "image/png",
    ".svg": "image/svg+xml",
    ".webp": "image/webp",
    ".woff": "font/woff",
    ".woff2": "font/woff2",
};

function dataUrl(file) {
    const mimeType = mimeTypes[extname(file).toLowerCase()] || "application/octet-stream";
    return `data:${mimeType};base64,${readFileSync(file).toString("base64")}`;
}

function replaceAll(source, search, replacement) {
    return source.split(search).join(replacement);
}

function escapeRegExp(value) {
    return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

let html = readFileSync(resolve(buildDir, "index.html"), "utf8");

html = html.replace(/<link\s+[^>]*rel=["']stylesheet["'][^>]*href=["']([^"']+)["'][^>]*>/gi, (_, href) => {
    const cssFile = resolve(buildDir, href.replace(/^\.\//, "").replace(/^\//, ""));
    if (!existsSync(cssFile)) throw new Error(`Missing stylesheet: ${href}`);
    const css = readFileSync(cssFile, "utf8").replaceAll("</style", "<\\/style");
    return `<style>${css}</style>`;
});

html = html.replace(/<script\s+([^>]*?)src=["']([^"']+)["']([^>]*)><\/script>/gi, (_, before, src, after) => {
    const scriptFile = resolve(buildDir, src.replace(/^\.\//, "").replace(/^\//, ""));
    if (!existsSync(scriptFile)) throw new Error(`Missing script: ${src}`);
    const script = readFileSync(scriptFile, "utf8").replaceAll("</script", "<\\/script");
    return `<script ${before}${after}>${script}</script>`;
});

const embeddedFiles = listFiles(buildDir)
    .filter((file) => file !== resolve(buildDir, "index.html"))
    .filter((file) => ![".css", ".js", ".map"].includes(extname(file).toLowerCase()))
    .sort((a, b) => b.length - a.length);

for (const file of embeddedFiles) {
    const relativePath = relative(buildDir, file).split("\\").join("/");
    const embedded = dataUrl(file);
    html = replaceAll(html, `./${relativePath}`, embedded);

    // Public files live at the build root. Also handle code that composes
    // BASE_URL and a filename at runtime instead of emitting one static URL.
    if (!relativePath.includes("/")) {
        html = replaceAll(html, `"${relativePath}"`, `"${embedded}"`);
        html = replaceAll(html, `'${relativePath}'`, `'${embedded}'`);
    }

    // Replace root-local URLs, but leave metadata URLs such as
    // https://goodlang.app/goodlang-new.png untouched.
    const rootLocalUrl = new RegExp(
        `(?<![A-Za-z0-9.:-])/${escapeRegExp(relativePath)}`,
        "g",
    );
    html = html.replace(rootLocalUrl, embedded);
}

const unresolvedAsset = html.match(/(?:src|href)=["']\.?\/(?!\/)[^"']+["']/i);
if (unresolvedAsset) {
    throw new Error(`Bundled HTML still contains a local asset URL: ${unresolvedAsset[0]}`);
}

mkdirSync(dirname(outputFile), {recursive: true});
writeFileSync(
    outputFile,
    `// Generated by npm run sync:web. Do not edit directly.\nexport default ${JSON.stringify(html)};\n`,
);
rmSync(buildDir, {recursive: true, force: true});

const sizeMb = (Buffer.byteLength(html) / 1024 / 1024).toFixed(2);
console.log(`Bundled GoodLang web build into ${relative(reactRoot, outputFile)} (${sizeMb} MB).`);
